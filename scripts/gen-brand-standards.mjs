// Generate supabase/patch-37-brand-standards.sql from the Sales workbook.
//
// Two things about the source shape drive the design here.
//
// 1. The workbook writes the same brand several ways — "2P" and "*2P",
//    "beW" and "BEW", ".LA GLACE" and "LA GLACE". 28 of its 483 brands collide
//    once case and the leading */."' markers are stripped, so the table is keyed
//    on the normalized form, not on the raw string, and carries the variants
//    alongside for reference.
//
// 2. Brand Standard is really keyed on (Company, Brand), not Brand alone: some
//    brands map to different standards depending on which company owns the SKU.
//    ICT and CM are the two that matter — 185 real orders between them — and
//    nothing on qc_orders identifies the owning company, so they cannot be
//    resolved per order. Those are marked ambiguous and the mail leaves the
//    brand exactly as QC typed it rather than guessing another customer's name.
//
// Run: node scripts/gen-brand-standards.mjs
import XLSX from 'xlsx';
import { writeFileSync } from 'fs';

const SRC = 'Sales/Company Brand Standard.xlsx';

/** Must stay identical to normalizeBrand() in web/api/notify-qc.ts. */
const normalize = (s) => String(s || '').replace(/^[*".'\s]+/, '').trim().toUpperCase();

const wb = XLSX.readFile(SRC);
const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]]);

const byKey = new Map();   // normalized brand -> { standards:Set, variants:Set }
for (const r of rows) {
  const brand = String(r['Brand'] || '').trim();
  const std = String(r['Brand Standard'] || '').trim();
  if (!brand || !std) continue;
  const key = normalize(brand);
  if (!key) continue;
  if (!byKey.has(key)) byKey.set(key, { standards: new Set(), variants: new Set() });
  byKey.get(key).standards.add(std);
  byKey.get(key).variants.add(brand);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const entries = [...byKey].sort((a, b) => a[0].localeCompare(b[0]));
const ambiguous = entries.filter(([, v]) => v.standards.size > 1);

const values = entries.map(([key, v]) => {
  const stds = [...v.standards];
  return `    (${q(key)}, ${q(stds[0])}, ${stds.length > 1}, ` +
         `${q(stds.join(' | '))}, ${q([...v.variants].join(' | '))})`;
});

const sql = `-- Patch 37: the Brand Standard lookup the QC mail checks before sending
--
-- Generated by scripts/gen-brand-standards.mjs from
--   ${SRC}
-- ${rows.length} rows in → ${entries.length} distinct brands out.
--
-- Keyed on the NORMALIZED brand (upper-case, leading * " . ' stripped) because
-- the workbook spells the same brand several ways — "2P"/"*2P", "beW"/"BEW",
-- ".LA GLACE"/"LA GLACE". 28 brands collide once normalized; keying on the raw
-- string would have made a unique index impossible.
--
-- ${ambiguous.length} brands map to more than one standard depending on the owning company.
-- They are stored with ambiguous = true, and the mail leaves those names alone.

begin;

create table if not exists public.brand_standards (
  brand_key      text primary key,     -- normalized: upper(), leading *".' stripped
  brand_standard text not null,
  ambiguous      boolean not null default false,
  candidates     text,                 -- every standard seen for this key
  variants       text,                 -- every raw spelling seen in the workbook
  updated_at     timestamptz not null default now()
);

comment on table public.brand_standards is
  'Brand → Brand Standard from Sales/Company Brand Standard.xlsx, keyed on the normalized brand. ambiguous = the workbook gives more than one answer and the owning company is needed to choose, so callers must leave the name as typed.';

delete from public.brand_standards;
insert into public.brand_standards (brand_key, brand_standard, ambiguous, candidates, variants) values
${values.join(',\n')};

alter table public.brand_standards enable row level security;
drop policy if exists "brand_standards_read" on public.brand_standards;
create policy "brand_standards_read" on public.brand_standards
  for select using (auth.role() = 'authenticated');

commit;

-- ---------------------------------------------------------------------------
-- Verify
-- ---------------------------------------------------------------------------

-- 1. Expect ${entries.length} rows, ${ambiguous.length} ambiguous.
select count(*) as "แบรนด์ทั้งหมด",
       count(*) filter (where ambiguous) as "กำกวม",
       count(*) filter (where brand_key <> upper(brand_standard)) as "ชื่อที่ต่างจากมาตรฐาน"
  from public.brand_standards;

-- 2. What the mail will now correct on real orders.
select o.brand as "ที่ QC พิมพ์", s.brand_standard as "มาตรฐาน", count(*) as "ใบ"
  from public.qc_orders o
  join public.brand_standards s
    on s.brand_key = upper(btrim(o.brand, '*". ''' ))
 where o.brand is not null
   and not s.ambiguous
   and o.brand <> s.brand_standard
 group by 1, 2
 order by 3 desc;

-- 3. Brands on real orders with no entry at all — these keep the typed name.
select o.brand as "ไม่พบในไฟล์มาตรฐาน", count(*) as "ใบ"
  from public.qc_orders o
  left join public.brand_standards s
    on s.brand_key = upper(btrim(o.brand, '*". ''' ))
 where o.brand is not null and s.brand_key is null
 group by 1
 order by 2 desc;
`;

writeFileSync('supabase/patch-37-brand-standards.sql', sql);
console.log(`workbook rows    : ${rows.length}`);
console.log(`distinct brands  : ${entries.length}`);
console.log(`ambiguous        : ${ambiguous.length}`);
ambiguous.forEach(([k, v]) => console.log(`   ${k} -> ${[...v.standards].join(' | ')}`));
console.log('written          : supabase/patch-37-brand-standards.sql');
